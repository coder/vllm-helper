// activate makes a profile the running one.
//
// This mirrors the CLI's activateProfile and must keep its ordering --
// record the active profile, tell integrations, then restart -- but none of
// its printing. Warnings come back as data so the panel can show them
// instead of writing to a terminal nobody is watching.
//
// It deliberately does not wait for the model to load. That takes minutes,
// far longer than a request should be held open, and the panel already polls
// status to show progress.
func (s *Server) activate(ctx context.Context, name string) ([]string, error) {
	p, err := profile.Load(s.cfg.Dirs, name)
	if err != nil {
		return nil, err
	}
	if err := writeActiveEnv(s.cfg, p); err != nil {
		return nil, err
	}

	// Plugins write to an io.Writer rather than assuming a terminal, so
	// their warnings can be captured and shown in the panel.
	var pluginOut bytes.Buffer
	plugin.Dispatch(ctx, &pluginOut, plugin.EventActivating, plugin.State{
		Config:  s.cfg,
		Name:    p.Name,
		Profile: p,
		BaseURL: fmt.Sprintf("http://localhost:%s/v1", s.cfg.Port()),
	})

	var warnings []string
	for _, line := range strings.Split(strings.TrimSpace(pluginOut.String()), "\n") {
		if line = strings.TrimSpace(line); line != "" {
			warnings = append(warnings, line)
		}
	}
	if err := s.privilegedCall(ctx, s.svc.Restart); err != nil {
		return warnings, err
	}
	return warnings, nil
}

// writeActiveEnv assembles the environment the service will start with:
// global config, then secrets, then the profile on top.
//
// Lifted from the CLI rather than shared, because exporting it would mean
// exporting a function whose output contains every secret on the machine.
// The 0600 mode is the important part and is preserved.
func writeActiveEnv(cfg *config.Config, p *profile.Profile) error {
	var b strings.Builder
	b.WriteString("# Generated by vllm-helper. Do not edit -- rewritten on every switch.\n")
	for _, f := range []*config.EnvFile{cfg.File, cfg.Secrets, p.File} {
		if f == nil {
			continue
		}
		for _, k := range f.Keys() {
			if v := f.Get(k); v != "" {
				fmt.Fprintf(&b, "%s=%s\n", k, config.Quote(v))
			}
		}
	}
	if err := os.MkdirAll(cfg.Dirs.State, 0o755); err != nil {
		return err
	}
	tmp := cfg.Dirs.ActiveEnvFile() + ".tmp"
	if err := os.WriteFile(tmp, []byte(b.String()), 0o600); err != nil {
		return err
	}
	if err := os.Rename(tmp, cfg.Dirs.ActiveEnvFile()); err != nil {
		return err
	}
	return os.WriteFile(cfg.Dirs.ActiveProfileFile(), []byte(p.Name+"\n"), 0o644)
}

func parseActive(cfg *config.Config) (*config.EnvFile, error) {
	return config.ParseEnvFile(cfg.Dirs.ActiveEnvFile())
}

// probeHealth asks vLLM whether it is serving. Lifted from the CLI; the 3s
// timeout matters because during a load the port is closed and this must
// fail fast rather than stall the status poll.
func probeHealth(port string) (int, bool) {
	client := &http.Client{Timeout: 3 * time.Second}
	resp, err := client.Get(fmt.Sprintf("http://localhost:%s/health", port))
	if err != nil {
		return 0, false
	}
	resp.Body.Close()
	return resp.StatusCode, resp.StatusCode == http.StatusOK
}

// lastMeaningfulLine picks the line most likely to say why the server died:
// a Python traceback ends with the exception, and vLLM's fatal startup
// errors are one-liners.
func lastMeaningfulLine(logs string) string {
	lines := strings.Split(logs, "\n")
	for i := len(lines) - 1; i >= 0; i-- {
		if line := strings.TrimSpace(lines[i]); line != "" {
			return line
		}
	}
	return ""
}

func hostname() string {
	h, err := os.Hostname()
	if err != nil {
		return ""
	}
	return filepath.Base(h)
}
